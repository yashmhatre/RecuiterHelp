"""Generate synthetic, pre-labelled emails for exercising the pipeline.

Modelled on real agency mail, in particular one from a Talent Acquisition team that read:

    Please find attached the JD and Intake Sheet for the Business Intelligence Consultant role.
    Must-have: Power BI + Databricks + SQL + AI/LLM Prompting
    Strongly preferred: DAX/Data Modeling + Power Query + Spark
    Good to have: Azure Databricks, MedTech/Life Sciences experience, Data Governance
    You are requested to please share relevant and aligned profiles...

WHAT THIS IS FOR
    Exercising the pipeline at volume before real labelled data exists: does classification hold
    up across intents, do the skill tiers parse, does matching pick the right people, does the
    validation gate fire where it should.

WHAT THIS IS NOT FOR
    Training a classifier, or quoting an accuracy number. Every email here came out of the same
    handful of templates I wrote, so a model trained on them learns this file rather than how
    recruiters write. It would score well and mean nothing. Real labelled mail is ticket P1-05
    and nothing here substitutes for it.

Output goes to `eval/dataset/labels.synthetic.jsonl`, deliberately not `labels.jsonl`, and every
record's `notes` field begins with SYNTHETIC so it is obvious wherever it surfaces.

    python eval/make_synthetic.py --count 60
"""

