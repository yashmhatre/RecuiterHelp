AUTH_PASS = (
    "mx.ourcompany.com; spf=pass smtp.mailfrom={d}; dkim=pass header.d={d}; dmarc=pass header.from={d}"
)


def _record(rid, sender, subject, body, headers, *, is_recruiter, intent, fields, note):
    return {
        "id": rid,
        "provider": "gmail",
        "headers": headers,
        "subject": subject,
        "body_text": body,
        "is_recruiter": is_recruiter,
        "intent": intent,
        "fields": fields,
        # Placeholder. These records are for classification and extraction, not match recall:
        # they reference no real candidate database.
        "expected_profile_ids": [1] if is_recruiter and intent in
                                {"new_requirement", "resume_request"} else [],
        "notes": f"{SYNTHETIC_MARKER} {note}",
    }


def generate(count: int, seed: int = 20261001) -> list[dict]:
    rng = random.Random(seed)
    records: list[dict] = []

    builders = [
        (_tiered_requirement, 0.30), (_plain_requirement, 0.25), (_resume_request, 0.18),
        (_follow_up, 0.10), (_interview, 0.09), (_vague, 0.08),
    ]
    weights = [w for _, w in builders]

    # Roughly 65% recruiter, 35% not: above the 25% non-recruiter floor the ticket requires.
    recruiter_count = int(count * 0.65)

    for i in range(recruiter_count):
        builder = rng.choices([b for b, _ in builders], weights=weights, k=1)[0]
        role = rng.choice(list(ROLES))
        must, pref, nice = ROLES[role]
        location = rng.choice(LOCATIONS)
        years = rng.choice([None, 3, 4, 5, 6, 8])
        domain, agency = rng.choice(AGENCIES)
        name = rng.choice(RECRUITERS)

        result = builder(rng, role, must, pref, nice, location, years)
        lines, intent = result[0], result[1]
        names = result[3] if len(result) > 3 else []

        if builder is not _vague:
            lines += ["", rng.choice(SIGNOFFS).format(name=name, agency=agency)]

        tiered = builder is _tiered_requirement
        subject = {
            "new_requirement": rng.choice([
                f"New opening | {role}", f"Requirement - {role} - {location}",
                f"Opportunity: {role} | {years}+ Years" if years else f"Opportunity: {role}",
                f"Urgent requirement - {role}",
            ]),
            "resume_request": rng.choice([f"Resume required - {role}", f"CV request | {role}"]),
            "follow_up": f"Re: {role} - following up",
            "interview": f"Interview scheduling | {role}",
            "other": rng.choice(["profiles", "CVs", "urgent"]),
        }[intent]

        local = name.split()[0].lower() + "." + name.split()[-1][0].lower()
        records.append(_record(
            f"syn-r-{i:03d}", f"{name} <{local}@{domain}>", subject, "\n".join(lines),
            {"from": f"{name} <{local}@{domain}>",
             "authentication-results": AUTH_PASS.format(d=domain)},
            is_recruiter=True, intent=intent,
            fields={
                "role": None if builder is _vague else role,
                "skills": [] if builder in (_vague, _follow_up, _interview)
                          else [s.lower() for s in (must + pref + nice if tiered else must + pref[:1])],
                "min_years_experience": float(years) if years and builder in
                                        (_tiered_requirement, _plain_requirement) else None,
                "location": None if builder in (_vague, _follow_up, _interview) else location,
                "candidate_names": names,
                "resume_requested": intent in {"resume_request", "new_requirement"},
            },
            note=f"shape={builder.__name__.lstrip('_')}",
        ))

    for i in range(count - recruiter_count):
        sender, subject, body, extra = NEGATIVES[i % len(NEGATIVES)]
        domain = sender.split("@")[-1].rstrip(">")
        headers = {"from": sender, "authentication-results": AUTH_PASS.format(d=domain)}
        headers.update(extra)
        records.append(_record(
            f"syn-n-{i:03d}", sender, subject, body, headers,
            is_recruiter=False, intent="other",
            fields={"role": None, "skills": [], "min_years_experience": None,
                    "location": None, "candidate_names": [], "resume_requested": False},
            note="negative",
        ))

    rng.shuffle(records)
    return records


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--count", type=int, default=60, help="How many records (default 60).")
    parser.add_argument("--seed", type=int, default=20261001, help="For reproducibility.")
    parser.add_argument("--out", type=Path, default=OUT_PATH)
    args = parser.parse_args(argv)

    records = generate(args.count, args.seed)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as handle:
        for record in records:
            handle.write(json.dumps(record, ensure_ascii=False) + "\n")

    recruiters = sum(1 for r in records if r["is_recruiter"])
    intents: dict[str, int] = {}
    for r in records:
        if r["is_recruiter"]:
            intents[r["intent"]] = intents.get(r["intent"], 0) + 1

    print(f"Wrote {len(records)} synthetic records to {args.out}")
    print(f"  recruiter      {recruiters} ({recruiters / len(records):.0%})")
    print(f"  not recruiter  {len(records) - recruiters}")
    print(f"  intents        {intents}")
    print("\n  These are for exercising the pipeline. Not for training, and not an accuracy")
    print("  number. Real labelled mail is ticket P1-05.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
