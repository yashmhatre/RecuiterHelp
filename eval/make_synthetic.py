def _tiered_requirement(rng, role, must, pref, nice, location, years):
    """The vcreatek shape: tiered skills, "share relevant profiles", often a JD attached."""
    attach = rng.random() < 0.5
    lines = ["Hi All" if rng.random() < 0.4 else "Hi Team", ""]
    if attach:
        lines += [f"Please find attached the JD and Intake Sheet for the {role} role.", ""]
    else:
        lines += [f"We have a new opening for a {role}. Details below.", ""]
    lines += [
        f"{rng.choice(MUST_HEADINGS)}: {' + '.join(must)}",
        f"{rng.choice(PREF_HEADINGS)}: {' + '.join(pref)}",
        f"{rng.choice(NICE_HEADINGS)}: {', '.join(nice)}",
        "",
        f"Location: {location}",
    ]
    if years:
        lines.append(f"Experience: {years}+ years")
    lines += [
        "",
        rng.choice([
            "You are requested to please share relevant and aligned profiles that closely match "
            "the above skills and requirements.",
            "Kindly share suitable profiles matching the above.",
            "Please share relevant profiles at the earliest.",
        ]),
        "",
        rng.choice([
            "Please ensure the candidates have strong hands-on experience with the must-have "
            "skills before sharing the profiles. Please treat this as urgent.",
            "Only profiles with hands-on experience in the mandatory skills, please.",
            "Immediate joiners preferred.",
        ]),
    ]
    return lines, "new_requirement", True


def _plain_requirement(rng, role, must, pref, nice, location, years):
    """No tiers, prose. The most common shape, and the one tier-aware code must not break."""
    skills = must + pref[:1]
    lines = [
        "Hi,",
        "",
        f"Hope you are doing well. We are looking for a {role} for one of our clients in "
        f"{location}.",
        "",
        f"The candidate should have strong experience in {', '.join(skills[:-1])} and "
        f"{skills[-1]}."
        + (f" We are looking at {years}+ years of experience." if years else ""),
        "",
        rng.choice([
            "Please share profiles of suitable candidates along with their current location, "
            "notice period and expected CTC.",
            "Kindly revert with matching profiles and availability.",
            "Do share a few relevant CVs if you have anyone available.",
        ]),
    ]
    return lines, "new_requirement", True


def _resume_request(rng, role, must, pref, nice, location, years):
    """Asks for a specific person, or for the profiles from an earlier thread."""
    named = rng.random() < 0.5
    if named:
        person = rng.choice(["Asha Menon", "Meera Iyer", "Rohit Nair", "Karan Shah", "Yash Mhatre"])
        lines = [
            "Hi,", "",
            rng.choice([
                f"Could you please share the updated resume of {person} for the client round?",
                f"Client has shortlisted {person}. Please send across the latest CV.",
                f"Can you send me {person}'s profile again? The earlier one did not come through.",
            ]),
        ]
        names = [person]
    else:
        lines = [
            "Hi,", "",
            f"Following up on the {role} position - could you share the CVs of the candidates "
            "you mentioned?",
        ]
        names = []
    lines += ["", rng.choice(["Thanks in advance.", "Appreciate a quick turnaround.", "Thanks!"])]
    return lines, "resume_request", True, names


def _follow_up(rng, role, must, pref, nice, location, years):
    lines = [
        "Hi,", "",
        rng.choice([
            f"Just following up on the {role} requirement I shared last week. Any update on "
            "profiles?",
            f"Checking in on the {role} role - the client is pushing for profiles by Friday.",
            f"Gentle reminder on the {role} position. Have you had a chance to look?",
        ]),
    ]
    return lines, "follow_up", True


def _interview(rng, role, must, pref, nice, location, years):
    person = rng.choice(["Asha Menon", "Meera Iyer", "Rohit Nair", "Karan Shah"])
    lines = [
        "Hi,", "",
        rng.choice([
            f"The client would like to schedule a technical round for {person} for the {role} "
            "position. Are they available on Thursday between 2 and 5 PM?",
            f"We have positive feedback on {person}. Client wants to proceed to round two. "
            "Please confirm availability this week.",
            f"Interview scheduled for {person} tomorrow at 11 AM. Please confirm.",
        ]),
    ]
    return lines, "interview", True, [person]


def _vague(rng, *_):
    """Too little to act on. Should produce no draft, not a guess."""
    lines = [rng.choice(["send profiles", "Any candidates?", "profiles pls", "Need CVs urgently"])]
    return lines, "other", True


